#!/usr/bin/env python3
"""Build the vendored Lucide SVG subset at exact LVGL pixel sizes.

Optional generation dependencies: Pillow and resvg-py. Ordinary firmware
builds use the checked-in C file and need neither packages nor network.
"""
from pathlib import Path
import hashlib
import io
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "firmware/p4_gesture/main/assets/icons"


def main():
    from PIL import Image
    import resvg_py

    manifest = json.loads((ASSETS / "manifest.json").read_text(encoding="utf-8"))
    output = ['/* Generated by tools/build_icons.py. Lucide ISC: assets/icons/LICENSE. */',
              '#include "meoave_icons.h"', '']
    table = []
    for name, spec in manifest["icons"].items():
        raw = (ASSETS / f"{name}.svg").read_bytes()
        if hashlib.sha256(raw).hexdigest() != spec["sha256"]:
            raise ValueError(f"SVG changed without updating manifest: {name}")
        svg = raw.decode().replace('currentColor', '#ffffff')
        for size in spec["sizes"]:
            # Oversample SVG geometry then downsample coverage, never enlarge a
            # small bitmap at runtime. Round caps and joins come from Lucide.
            png = resvg_py.svg_to_bytes(svg_string=svg, width=size*4, height=size*4)
            alpha = Image.open(io.BytesIO(png)).getchannel("A").resize((size,size),Image.Resampling.LANCZOS)
            data = alpha.tobytes()
            symbol = name.replace('-', '_') + f"_{size}"
            output.append(f"static const uint8_t pixels_{symbol}[] = {{")
            for i in range(0,len(data),24):
                output.append('    '+','.join(f'0x{v:02x}' for v in data[i:i+24])+',')
            output += ['};', f'static const lv_image_dsc_t image_{symbol} = {{',
                       f'    .header = {{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w={size},.h={size},.stride={size}}},',
                       f'    .data_size={len(data)}, .data=pixels_{symbol}', '};', '']
            table.append((spec["kind"],size,symbol))
    output += ['const lv_image_dsc_t *meo_icon_asset(icon_kind_t kind, int size)', '{']
    for kind,size,symbol in table:
        output.append(f'    if (kind=={kind} && size=={size}) return &image_{symbol};')
    output += ['    return NULL;', '}', '']
    (ASSETS.parents[1] / "meoave_icons.c").write_text('\n'.join(output),encoding='utf-8')
    print(f"Generated {len(table)} native-size Lucide masks")


if __name__ == '__main__':
    main()
