"""Render actual LVGL test PPMs into square-panel PNG previews and animation.

Usage: python tests/desktop/render_preview.py test-results/ui-desktop [baseline-folder]
Requires Pillow. Source PPMs are generated by meoave_visual_test, not mockups.
"""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

folder = Path(sys.argv[1])
backdrop = '#252525'


def panel(path):
    # The physical display is square. Preserve every pixel, including corners;
    # rounded app cards are drawn by LVGL, not by a preview-only screen mask.
    with Image.open(path) as source:
        image = source.convert('RGB')
    assert image.size == (460, 460), f'Unexpected panel size: {image.size}'
    return image


files = sorted(folder.glob('[0-9][0-9]-*.ppm'))
sheet = Image.new('RGB', (4*480, ((len(files)+3)//4)*500), backdrop)
for i, path in enumerate(files):
    Image.open(path).save(path.with_suffix('.png'))
    tile = panel(path)
    tile.save(path.with_name(path.stem+'-square.png'))
    x, y = (i % 4)*480+10, (i//4)*500+10
    sheet.paste(tile, (x, y))
    ImageDraw.Draw(sheet).text((x+10, y+465), path.stem, fill='#c4c4c4')
sheet.save(folder/'contact-sheet.png')
preview = Image.new('RGB', (940, 940), backdrop)
tracking = (folder/'05-breathe-waiting.ppm').exists()
breath_preview = '05-breathe-waiting' if tracking else '06-breathe-inhale'
for i, name in enumerate(('01-eyes', '02-apps', '03-settings', breath_preview)):
    preview.paste(panel(folder/(name+'.ppm')), ((i%2)*470+5, (i//2)*470+5))
preview.save(folder/'preview.png')
if len(sys.argv) > 2:
    # Compare actual renders, never a separately styled concept mockup. Labels
    # live outside the untouched 460px panels, not in the product UI.
    baseline = Path(sys.argv[2])
    comparison = Image.new('RGB', (968, 1024), backdrop)
    caption = ImageFont.load_default(size=28)
    pen = ImageDraw.Draw(comparison)
    pen.text((16, 22), 'BASELINE', font=caption, fill='#c4c4c4')
    pen.text((492, 22), 'PROPOSED / NOT FLASHED', font=caption, fill='#ffffff')
    for row, (old_name, new_name) in enumerate((('02-apps','02-apps'),
                       ('06-breathe-inhale',breath_preview))):
        comparison.paste(panel(baseline/(old_name+'.ppm')), (16, 72+row*476))
        comparison.paste(panel(folder/(new_name+'.ppm')), (492, 72+row*476))
    comparison.save(folder/'before-after.png')
interaction = Image.new('RGB',(1410,940),backdrop)
for i,name in enumerate(('02-apps','03-settings','15-display-brightness','16-accessibility','04-wifi-unavailable', '05-breathe-waiting' if tracking else '05-breathe-ready')):
    interaction.paste(panel(folder/(name+'.ppm')),((i%3)*470+5,(i//3)*470+5))
interaction.save(folder/'interaction-preview.png')
frames = [panel(p).resize((320,320), Image.Resampling.LANCZOS)
          for p in sorted(folder.glob('motion-*.ppm'))]
if frames:
    frames[0].save(folder/'breathe.gif', save_all=True, append_images=frames[1:],
                   duration=100, loop=0)
simulated = [panel(p).resize((360,360), Image.Resampling.LANCZOS)
             for p in sorted(folder.glob('simulated-motion-*.ppm'))]
if simulated:
    # The filename and presentation label explicitly say simulated; every GIF
    # pixel is the actual square LVGL screen, with no fake top status bar.
    simulated[0].save(folder/'breathe-simulated.gif',save_all=True,append_images=simulated[1:],
                    duration=100,loop=0)
expressions = ('17-calm','18-happy','19-curious','20-sleepy','21-surprised','22-wink','23-sad')
if all((folder/(name+'.ppm')).exists() for name in expressions):
    eyes = Image.new('RGB',(4*360,2*390),backdrop)
    for i,name in enumerate(expressions):
        eyes.paste(panel(folder/(name+'.ppm')).resize((340,340),Image.Resampling.LANCZOS),
                   ((i%4)*360+10,(i//4)*390+10))
        ImageDraw.Draw(eyes).text(((i%4)*360+25,(i//4)*390+360),name[3:],fill='#c4c4c4')
    eyes.save(folder/'expressions-preview.png')
eye_frames = [panel(p).resize((360,360),Image.Resampling.LANCZOS)
              for p in sorted(folder.glob('eyes-motion-*.ppm'))]
if eye_frames:
    eye_frames[0].save(folder/'eyes.gif',save_all=True,append_images=eye_frames[1:],duration=80,loop=0)
cards = ('24-apps-settings', '02-apps', '25-apps-breathe')
if all((folder/(name+'.ppm')).exists() for name in cards):
    strip = Image.new('RGB', (1410,470), backdrop)
    for i,name in enumerate(cards):
        strip.paste(panel(folder/(name+'.ppm')), (i*470+5,5))
    strip.save(folder/'carousel-preview.png')
    strip.save(folder/'carousel-square-preview.png')
carousel = [panel(p) for p in sorted(folder.glob('carousel-*.ppm'))]
if carousel:
    # GIF timing is in 10ms units. WebP preserves the 16ms desktop samples;
    # neither format is a measurement of real hardware presentation rate.
    carousel[0].save(folder/'carousel.webp',save_all=True,append_images=carousel[1:],
                     duration=16,loop=0,lossless=True,method=1)
    carousel[0].save(folder/'carousel-square.webp',save_all=True,append_images=carousel[1:],
                     duration=16,loop=0,lossless=True,method=1)
    carousel[0].save(folder/'carousel.gif',save_all=True,append_images=carousel[1:],
                     duration=20,loop=0)
print('Actual LVGL square-panel previews: '+str(folder.resolve()))
